// Helper to calculate exact consolidated metrics from this deterministic dataset
export const calculateDashboardMetrics = (
  apps: Application[] = MOCK_APPLICATIONS,
  evcs: EVCInspection[] = MOCK_EVC_INSPECTIONS,
  comps: ComplianceItem[] = MOCK_COMPLIANCE_ITEMS,
  docs: DocumentValidityItem[] = MOCK_DOCUMENT_VALIDITY_ITEMS
): DashboardMetrics => {
  const stageDistribution: Record<any, number> = {
    SUBMITTED: 0,
    SCRUTINY: 0,
    RE_SCRUTINY: 0,
    EVC_SCHEDULED: 0,
    EVC_COMPLETED: 0,
    SHC_HEARING: 0,
    SAC_APPEAL: 0,
    APPROVED_CONDITIONAL: 0,
    APPROVAL_GRANTED: 0,
    REJECTED: 0,
  };

  const categoryDistribution: Record<any, number> = {
    NEW_INSTITUTE: 0,
    EOA_EXISTING: 0,
    INTAKE_INCREASE: 0,
    SUPERNUMERARY_SEATS: 0,
    CHANGE_OF_SITE: 0,
    WOMEN_TO_COED: 0,
    CLOSURE: 0,
  };

  let totalAgeingSum = 0;
  let pendingScrutinyCount = 0;
  let overdueTasksCount = 0;

  for (const app of apps) {
    if (stageDistribution[app.currentStage] !== undefined) {
      stageDistribution[app.currentStage]++;
    }
    if (categoryDistribution[app.category] !== undefined) {
      categoryDistribution[app.category]++;
    }
    totalAgeingSum += app.totalAgeingDays;

    if (app.currentStage === 'SCRUTINY' || app.currentStage === 'RE_SCRUTINY') {
      pendingScrutinyCount++;
    }

    if (app.priority === 'CRITICAL_OVERDUE' || app.stageAgeingDays > 7) {
      overdueTasksCount++;
    }
  }

  const evcScheduledCount = evcs.filter(
    (e) => e.status === 'SCHEDULED' || e.status === 'CONSTITUTED'
  ).length;
  const evcOverdueReportsCount = evcs.filter((e) => e.isOverdue || e.status === 'REPORT_OVERDUE').length;

  const complianceDueSoonCount = comps.filter(
    (c) => c.status === 'ACTIVE_PENDING' && c.daysRemaining > 0 && c.daysRemaining <= 30
  ).length;
  const complianceOverdueCount = comps.filter((c) => c.isOverdue || c.daysRemaining < 0).length;

  const documentValidityExpiringSoonCount = docs.filter(
    (d) => d.validityStatus === 'EXPIRING_SOON' || (d.validityStatus === 'CRITICAL_WARNING' && d.daysToExpiry > 0)
  ).length;
  const documentValidityExpiredCount = docs.filter((d) => d.validityStatus === 'EXPIRED' || d.daysToExpiry <= 0).length;

  const criticalAlertCount =
    overdueTasksCount + evcOverdueReportsCount + complianceOverdueCount + documentValidityExpiredCount;

  return {
    totalApplications: apps.length,
    stageDistribution,
    categoryDistribution,
    pendingScrutinyCount,
    overdueTasksCount,
    evcScheduledCount,
    evcOverdueReportsCount,
    complianceDueSoonCount,
    complianceOverdueCount,
    documentValidityExpiringSoonCount,
    documentValidityExpiredCount,
    averageAgeingDays: Math.round(totalAgeingSum / (apps.length || 1)),
    criticalAlertCount,
  };
};

export const MOCK_DASHBOARD_METRICS = calculateDashboardMetrics();
